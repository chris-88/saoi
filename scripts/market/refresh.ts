/**
 * Refresh Saoi's market data from each provider's public website (`providers.ts`).
 *
 *   npm run market:refresh                     fetch, parse, validate and print the diff; writes nothing
 *   npm run market:refresh -- --snapshot       also rewrite each provider's committed snapshot
 *   npm run market:refresh -- --db             also record the result in market_products
 *   npm run market:refresh -- --accept-removals  let a product that has gone from the site be retired
 *   npm run market:refresh -- --provider boi   run one provider only
 *
 * --db needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the environment. Against the live
 * stack on this machine:
 *
 *   SUPABASE_URL=http://127.0.0.1:8002 \
 *   SUPABASE_SERVICE_ROLE_KEY="$(pass show infra/saoi/SERVICE_ROLE_KEY | head -1)" \
 *   npm run market:refresh -- --db
 *
 * The diff is against the database with --db, otherwise against the committed snapshot.
 *
 * All or nothing per provider. Every page of a provider is fetched and parsed before anything
 * of that provider's is written; one page that cannot be read, one sentence a parser cannot
 * find, or one record that fails the schema means nothing is written for that provider. A
 * product whose page has gone (404) does the same unless --accept-removals says it is expected.
 * One provider failing never stops another from being written.
 *
 * Exit codes: 0 when every provider was read (and written, if asked); 1 when any provider
 * failed, or the run could not start (bad arguments, no database credentials).
 *
 * Polite by construction: each provider's robots.txt is read first and every URL checked
 * against it, the requests go one at a time with a pause between them, and the user agent says
 * who is asking.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createClient } from '@supabase/supabase-js'
import type { Database, Json } from '../../supabase/functions/_shared/db/database.types.ts'
import {
  MARKET_COLUMNS,
  productsFromRows,
  rowFor,
} from '../../supabase/functions/_shared/db/market.ts'
import {
  type MarketProduct,
  type MarketSnapshot,
  marketSnapshotSchema,
} from '../../supabase/functions/_shared/market/schema.ts'
import { ParseError } from './boi.ts'
import { describeDiff, diffMarket } from './diff.ts'
import type { MarketProvider } from './provider.ts'
import { MARKET_PROVIDERS } from './providers.ts'
import { robotsAllows } from './robots.ts'
import { runProviders } from './run.ts'

const USER_AGENT = 'saoi-market-refresh/0.1 (+https://saoi.ie; one run, a handful of pages)'
const PAUSE_MS = 2_000

const argv = process.argv.slice(2)
const args = new Set(argv)
const writeSnapshot = args.has('--snapshot')
const writeDb = args.has('--db')
const acceptRemovals = args.has('--accept-removals')
const only = argv[argv.indexOf('--provider') + 1]

const pause = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms))

type Page = { readonly status: number; readonly html: string }
type Db = ReturnType<typeof createClient<Database>>

async function get(url: string): Promise<Page> {
  const response = await fetch(url, {
    headers: { 'user-agent': USER_AGENT, accept: 'text/html,text/plain' },
    redirect: 'follow',
    signal: AbortSignal.timeout(20_000),
  })
  return { status: response.status, html: await response.text() }
}

function databaseClient(): Db {
  const url = process.env['SUPABASE_URL']
  const key = process.env['SUPABASE_SERVICE_ROLE_KEY']
  if (url === undefined || key === undefined || url === '' || key === '') {
    throw new Error('--db needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY')
  }
  return createClient<Database>(url, key, { auth: { persistSession: false } })
}

function snapshotFile(provider: string): string {
  return fileURLToPath(
    new URL(`../../supabase/functions/_shared/market/${provider}.snapshot.ts`, import.meta.url),
  )
}

function snapshotSource(snapshot: MarketSnapshot): string {
  return [
    '// GENERATED by scripts/market/refresh.ts (npm run market:refresh -- --snapshot). Do not edit by hand.',
    '//',
    `// ${snapshot.provider}: the published rates and conditions for the products Saoi models, read`,
    '// from the provider’s public website. The fallback when `market_products` is empty, and the',
    '// record in git of what the site said on the date below.',
    '',
    "import type { MarketSnapshot } from './schema.ts'",
    '',
    `export const ${snapshot.provider}Snapshot: MarketSnapshot = ${JSON.stringify(snapshot, null, 2)}`,
    '',
  ].join('\n')
}

/** One provider, start to finish. True when it was read and written as asked. */
async function refreshProvider(provider: MarketProvider, db: Db | null): Promise<boolean> {
  const name = provider.provider
  const checkedAt = new Date().toISOString()
  const failures: string[] = []
  const gone: string[] = []

  // ---- robots.txt first --------------------------------------------------------------
  const robots = await get(`${provider.origin}/robots.txt`)
  if (robots.status !== 200) {
    console.error(`${name}: robots.txt answered ${String(robots.status)}; not fetching anything`)
    return false
  }
  const urls = [
    ...(provider.rateSheet === undefined ? [] : [provider.rateSheet.page]),
    ...provider.sources.map((source) => source.url),
  ]
  const refused = urls.filter((url) => !robotsAllows(robots.html, new URL(url).pathname))
  if (refused.length > 0) {
    console.error(`${name}: robots.txt disallows ${refused.join(', ')}; not fetching anything`)
    return false
  }

  // ---- the pages, one at a time ------------------------------------------------------
  let rateSheet: MarketSnapshot['rateSheet'] = null
  if (provider.rateSheet !== undefined) {
    await pause(PAUSE_MS)
    const page = await get(provider.rateSheet.page)
    rateSheet = page.status === 200 ? provider.rateSheet.read(page.html) : null
    if (rateSheet === null) console.warn(`${name}: no rate sheet on ${provider.rateSheet.page}`)
  }

  const products: MarketProduct[] = []
  for (const source of provider.sources) {
    await pause(PAUSE_MS)
    let page: Page
    try {
      page = await get(source.url)
    } catch (error) {
      failures.push(`${source.productId}: fetch failed (${String(error)})`)
      continue
    }
    if (page.status === 404 || page.status === 410) {
      gone.push(source.productId)
      continue
    }
    if (page.status !== 200) {
      failures.push(`${source.productId}: ${source.url} answered ${String(page.status)}`)
      continue
    }
    try {
      products.push({
        provider: name,
        productId: source.productId,
        category: source.category,
        ...source.parse(page.html),
        sourceUrl: source.url,
        checkedAt,
        effectiveFrom: null,
      })
    } catch (error) {
      if (!(error instanceof ParseError)) throw error
      failures.push(`${source.productId}: ${error.message} on ${source.url}`)
    }
  }

  // ---- validate the whole result -----------------------------------------------------
  const snapshot = marketSnapshotSchema.safeParse({
    provider: name,
    checkedAt,
    rateSheet,
    products,
  })
  if (!snapshot.success) {
    for (const issue of snapshot.error.issues) {
      failures.push(`schema: ${issue.path.join('.')}: ${issue.message}`)
    }
  }

  // ---- the diff ----------------------------------------------------------------------
  let baseline: readonly MarketProduct[] = provider.snapshot.products
  let baselineName = `the committed snapshot (${provider.snapshot.checkedAt})`
  if (db !== null) {
    const result = await db
      .from('market_products')
      .select(MARKET_COLUMNS)
      .eq('provider', name)
      .is('superseded_at', null)
    if (result.error !== null) {
      console.error(`${name}: reading market_products: ${result.error.message}`)
      return false
    }
    baseline = productsFromRows(result.data)
    baselineName = `market_products (${String(baseline.length)} current rows)`
  }

  const failed = (productId: string) =>
    failures.some((failure) => failure.startsWith(`${productId}:`))
  const diff = diffMarket(baseline, products)
  const disappeared = [
    ...new Set([...gone, ...diff.disappeared.filter((productId) => !failed(productId))]),
  ]

  console.log(`\n${name}: checked ${checkedAt}, against ${baselineName}`)
  if (rateSheet !== null) console.log(`rate sheet: ${rateSheet.asOf ?? 'undated'} ${rateSheet.url}`)
  for (const line of describeDiff({ ...diff, disappeared: [] })) console.log(line)
  for (const productId of disappeared) console.log(`GONE     ${productId}`)
  for (const failure of failures) console.error(`COULD NOT PARSE  ${name} ${failure}`)

  if (failures.length > 0 || !snapshot.success) {
    console.error(`${name}: ${String(failures.length)} failure(s). Nothing written for ${name}.`)
    return false
  }
  if (disappeared.length > 0 && !acceptRemovals) {
    console.error(
      `${name}: a product has gone from the site. Nothing written for ${name}. Check the ` +
        'page, then run again with --accept-removals to retire it.',
    )
    return false
  }

  // ---- write -------------------------------------------------------------------------
  if (db !== null) {
    const result = await db.rpc('market_record_refresh', {
      p_provider: name,
      // Validated above; JSON all the way down.
      p_products: snapshot.data.products.map(rowFor) as unknown as Json,
      p_retired: disappeared,
    })
    if (result.error !== null) {
      console.error(`${name}: market_record_refresh: ${result.error.message}`)
      return false
    }
    console.log(`market_products: ${JSON.stringify(result.data)}`)
  }

  if (writeSnapshot) {
    const file = snapshotFile(name)
    writeFileSync(file, snapshotSource(snapshot.data))
    execFileSync('npx', ['prettier', '--write', '--log-level', 'warn', file], { stdio: 'inherit' })
    console.log(`wrote ${file}`)
  }
  return true
}

async function main(): Promise<number> {
  const providers = args.has('--provider')
    ? MARKET_PROVIDERS.filter((p) => p.provider === only)
    : MARKET_PROVIDERS
  if (providers.length === 0) {
    console.error(`No provider called ${String(only)}.`)
    return 1
  }

  const db = writeDb ? databaseClient() : null
  const failed = await runProviders(providers, (provider) => refreshProvider(provider, db))

  if (db === null && !writeSnapshot) console.log('\nDry run: nothing written.')
  if (failed.length > 0) {
    console.error(`\nFailed: ${failed.join(', ')}. Every other provider was handled.`)
    return 1
  }
  return 0
}

main().then(
  (code) => process.exit(code),
  (error: unknown) => {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  },
)
