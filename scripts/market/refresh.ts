/**
 * Refresh Saoi's market data from Bank of Ireland's public website.
 *
 *   npm run market:refresh                     fetch, parse, validate and print the diff; writes nothing
 *   npm run market:refresh -- --snapshot       also rewrite the committed snapshot (boi.snapshot.ts)
 *   npm run market:refresh -- --db             also record the result in market_products
 *   npm run market:refresh -- --accept-removals  let a product that has gone from the site be retired
 *
 * --db needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the environment. Against the live
 * stack on this machine:
 *
 *   SUPABASE_URL=http://127.0.0.1:8002 \
 *   SUPABASE_SERVICE_ROLE_KEY="$(pass show infra/saoi/SERVICE_ROLE_KEY | head -1)" \
 *   npm run market:refresh -- --db
 *
 * The diff is against the database with --db, otherwise against the committed snapshot.
 *
 * All or nothing. Every page is fetched and parsed before anything is written; one page that
 * cannot be read, one sentence a parser cannot find, or one record that fails the schema stops
 * the run with exit 1 and nothing written. A product whose page has gone (404) is reported and
 * also stops the run, unless --accept-removals says that is expected.
 *
 * Polite by construction: robots.txt is read first and every URL checked against it, the
 * requests go one at a time with a pause between them, seven pages in all, and the user agent
 * says who is asking.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createClient } from '@supabase/supabase-js'
import type { Database, Json } from '../../supabase/functions/_shared/db/database.types.ts'
import {
  MARKET_COLUMNS,
  productsFromRows,
  rowFor,
} from '../../supabase/functions/_shared/db/market.ts'
import {
  BOI_ORIGIN,
  BOI_RATE_SHEET_PAGE,
  BOI_SOURCES,
} from '../../supabase/functions/_shared/market/boi-sources.ts'
import { boiSnapshot } from '../../supabase/functions/_shared/market/boi.snapshot.ts'
import {
  type MarketProduct,
  type MarketSnapshot,
  marketSnapshotSchema,
} from '../../supabase/functions/_shared/market/schema.ts'
import { BOI_PARSERS, ParseError, rateSheetOf } from './boi.ts'
import { describeDiff, diffMarket } from './diff.ts'
import { robotsAllows } from './robots.ts'

const USER_AGENT = 'saoi-market-refresh/0.1 (+https://saoi.ie; one run, a handful of pages)'
const PAUSE_MS = 2_000
const SNAPSHOT_FILE = fileURLToPath(
  new URL('../../supabase/functions/_shared/market/boi.snapshot.ts', import.meta.url),
)

const args = new Set(process.argv.slice(2))
const writeSnapshot = args.has('--snapshot')
const writeDb = args.has('--db')
const acceptRemovals = args.has('--accept-removals')

const pause = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms))

type Page = { readonly status: number; readonly html: string }

async function get(url: string): Promise<Page> {
  const response = await fetch(url, {
    headers: { 'user-agent': USER_AGENT, accept: 'text/html,text/plain' },
    redirect: 'follow',
    signal: AbortSignal.timeout(20_000),
  })
  return { status: response.status, html: await response.text() }
}

function databaseClient() {
  const url = process.env['SUPABASE_URL']
  const key = process.env['SUPABASE_SERVICE_ROLE_KEY']
  if (url === undefined || key === undefined || url === '' || key === '') {
    throw new Error('--db needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY')
  }
  return createClient<Database>(url, key, { auth: { persistSession: false } })
}

function snapshotSource(snapshot: MarketSnapshot): string {
  return [
    '// GENERATED by scripts/market/refresh.ts (npm run market:refresh -- --snapshot). Do not edit by hand.',
    '//',
    "// Bank of Ireland's published rates and conditions for the products Saoi models, read from",
    '// personalbanking.bankofireland.com. The fallback when `market_products` is empty, and the',
    '// record in git of what the site said on the date below.',
    '',
    "import type { MarketSnapshot } from './schema.ts'",
    '',
    `export const boiSnapshot: MarketSnapshot = ${JSON.stringify(snapshot, null, 2)}`,
    '',
  ].join('\n')
}

async function main(): Promise<number> {
  const checkedAt = new Date().toISOString()
  const failures: string[] = []
  const gone: string[] = []

  // ---- robots.txt first --------------------------------------------------------------
  const robots = await get(`${BOI_ORIGIN}/robots.txt`)
  if (robots.status !== 200) throw new Error(`robots.txt answered ${String(robots.status)}`)
  const urls = [BOI_RATE_SHEET_PAGE, ...BOI_SOURCES.map((source) => source.url)]
  for (const url of urls) {
    if (!robotsAllows(robots.html, new URL(url).pathname)) {
      throw new Error(`robots.txt disallows ${url}; not fetching anything`)
    }
  }

  // ---- the pages, one at a time ------------------------------------------------------
  await pause(PAUSE_MS)
  const sheetPage = await get(BOI_RATE_SHEET_PAGE)
  const rateSheet = sheetPage.status === 200 ? rateSheetOf(sheetPage.html) : null
  if (rateSheet === null) console.warn(`warning: no rate sheet link on ${BOI_RATE_SHEET_PAGE}`)

  const products: MarketProduct[] = []
  for (const source of BOI_SOURCES) {
    await pause(PAUSE_MS)
    const parser = BOI_PARSERS[source.productId]
    if (parser === undefined) {
      failures.push(`${source.productId}: no parser`)
      continue
    }
    let page: Page
    try {
      page = await get(source.url)
    } catch (error) {
      failures.push(`${source.productId}: fetch failed (${String(error)})`)
      continue
    }
    if (page.status === 404 || page.status === 410) {
      gone.push(source.productId)
      continue
    }
    if (page.status !== 200) {
      failures.push(`${source.productId}: ${source.url} answered ${String(page.status)}`)
      continue
    }
    try {
      const parsed = parser(page.html)
      products.push({
        provider: 'boi',
        productId: source.productId,
        category: source.category,
        ...parsed,
        sourceUrl: source.url,
        checkedAt,
        effectiveFrom: null,
      })
    } catch (error) {
      if (!(error instanceof ParseError)) throw error
      failures.push(`${source.productId}: ${error.message} on ${source.url}`)
    }
  }

  // ---- validate the whole result -----------------------------------------------------
  const snapshot = marketSnapshotSchema.safeParse({
    provider: 'boi',
    checkedAt,
    rateSheet,
    products,
  })
  if (!snapshot.success) {
    for (const issue of snapshot.error.issues) {
      failures.push(`schema: ${issue.path.join('.')}: ${issue.message}`)
    }
  }

  // ---- the diff ----------------------------------------------------------------------
  const db = writeDb ? databaseClient() : null
  let baseline: readonly MarketProduct[] = boiSnapshot.products
  let baselineName = `the committed snapshot (${boiSnapshot.checkedAt})`
  if (db !== null) {
    const result = await db
      .from('market_products')
      .select(MARKET_COLUMNS)
      .eq('provider', 'boi')
      .is('superseded_at', null)
    if (result.error !== null) throw new Error(`reading market_products: ${result.error.message}`)
    baseline = productsFromRows(result.data)
    baselineName = `market_products (${String(baseline.length)} current rows)`
  }

  const diff = diffMarket(baseline, products)
  const disappeared = [...new Set([...gone, ...diff.disappeared.filter((id) => !failed(id))])]

  function failed(productId: string): boolean {
    return failures.some((failure) => failure.startsWith(`${productId}:`))
  }

  console.log(`Bank of Ireland, checked ${checkedAt}, against ${baselineName}`)
  if (rateSheet !== null) console.log(`rate sheet: ${rateSheet.asOf ?? 'undated'} ${rateSheet.url}`)
  for (const line of describeDiff({ ...diff, disappeared: [] })) console.log(line)
  for (const productId of disappeared) console.log(`GONE     ${productId}`)
  for (const failure of failures) console.error(`COULD NOT PARSE  ${failure}`)

  if (failures.length > 0) {
    console.error(`\n${String(failures.length)} failure(s). Nothing written.`)
    return 1
  }
  if (disappeared.length > 0 && !acceptRemovals) {
    console.error(
      '\nA product has gone from the site. Nothing written. Check the page, then run again ' +
        'with --accept-removals to retire it.',
    )
    return 1
  }
  if (!snapshot.success) return 1

  // ---- write -------------------------------------------------------------------------
  if (db !== null) {
    const result = await db.rpc('market_record_refresh', {
      p_provider: 'boi',
      // Validated above; JSON all the way down.
      p_products: snapshot.data.products.map(rowFor) as unknown as Json,
      p_retired: disappeared,
    })
    if (result.error !== null) throw new Error(`market_record_refresh: ${result.error.message}`)
    console.log(`market_products: ${JSON.stringify(result.data)}`)
  }

  if (writeSnapshot) {
    writeFileSync(SNAPSHOT_FILE, snapshotSource(snapshot.data))
    execFileSync('npx', ['prettier', '--write', '--log-level', 'warn', SNAPSHOT_FILE], {
      stdio: 'inherit',
    })
    console.log(`wrote ${SNAPSHOT_FILE}`)
  }

  if (db === null && !writeSnapshot) console.log('\nDry run: nothing written.')
  return 0
}

main().then(
  (code) => process.exit(code),
  (error: unknown) => {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  },
)
